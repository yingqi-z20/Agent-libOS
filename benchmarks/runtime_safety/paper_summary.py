from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from agent_libos.utils.serde import to_jsonable
from benchmarks.runtime_safety.metrics import collect_metrics

BASELINE_RUNNERS = (
    "direct_tool_wrapper",
    "confirmation_wrapper",
    "sandbox_only",
    "agent_libos_full",
)
ABLATION_RUNNERS = (
    "agent_libos_full",
    "no_primitive_approval",
    "no_fork_attenuation",
    "no_audit_linkage",
    "no_namespace_isolation",
)
ABLATION_TABLE_RUNNERS = (
    "agent_libos_full",
    "no_primitive_approval",
    "no_fork_attenuation",
)
RUNNER_LABELS = {
    "agent_libos_full": "Full Agent libOS",
    "confirmation_wrapper": "Confirm wrapper",
    "direct_tool_wrapper": "Direct wrapper",
    "sandbox_only": "Sandbox-only",
    "no_audit_linkage": "No audit linkage",
    "no_fork_attenuation": "No fork attenuation",
    "no_namespace_isolation": "No namespace isolation",
    "no_primitive_approval": "No primitive approval",
}


def build_paper_summary(run_dir: str | Path) -> dict[str, Any]:
    root = Path(run_dir)
    metrics = collect_metrics(root)
    effects = _read_jsonl(root / "effects.jsonl")
    rows_by_runner = {str(row["runner"]): row for row in metrics["rows"]}
    effect_counts = _effect_counts_by_runner(effects)
    full = rows_by_runner.get("agent_libos_full", {})
    allowed_denials = [
        _compact_effect(effect)
        for effect in effects
        if effect.get("runner") == "agent_libos_full"
        and effect.get("denied")
        and effect.get("classification") == "allowed"
    ]
    forbidden_denials = [
        _compact_effect(effect)
        for effect in effects
        if effect.get("runner") == "agent_libos_full"
        and effect.get("denied")
        and effect.get("classification") == "forbidden"
    ]
    return {
        "run_dir": str(root),
        "baseline_rows": [
            _row(rows_by_runner[name], effect_counts.get(name, {}))
            for name in BASELINE_RUNNERS
            if name in rows_by_runner
        ],
        "ablation_rows": [
            _ablation_row(rows_by_runner[name], full, effect_counts.get(name, {}))
            for name in ABLATION_RUNNERS
            if name in rows_by_runner
        ],
        "full_runner": _row(full, effect_counts.get("agent_libos_full", {})) if full else {},
        "full_allowed_denials": allowed_denials,
        "full_forbidden_denials": forbidden_denials,
        "self_evolution_counts": _self_evolution_counts(full),
        "result_count": metrics["result_count"],
        "effect_count": metrics["effect_count"],
    }


def write_paper_summary(
    run_dir: str | Path,
    *,
    json_out: str | Path | None = None,
    tex_out: str | Path | None = None,
) -> dict[str, Any]:
    root = Path(run_dir)
    summary = build_paper_summary(root)
    if json_out is None:
        json_out = root / "paper_summary.json"
    if tex_out is None:
        tex_out = root / "paper_tables.tex"
    Path(json_out).write_text(json.dumps(to_jsonable(summary), indent=2, ensure_ascii=False), encoding="utf-8")
    Path(tex_out).write_text(render_latex_tables(summary), encoding="utf-8")
    return summary


def render_latex_tables(summary: dict[str, Any]) -> str:
    return "\n\n".join(
        [
            _render_baseline_table(summary.get("baseline_rows", [])),
            _render_ablation_table(summary.get("ablation_rows", [])),
            _render_denial_comment(summary),
            "",
        ]
    )


def _render_baseline_table(rows: list[dict[str, Any]]) -> str:
    lines = [
        "% Generated by experiments/paper_runtime_safety_summary.py.",
        "\\begin{tabular}{@{}lrrrrr@{}}",
        "\\toprule",
        "\\textbf{Runner} & \\textbf{Tasks} & \\textbf{Effects} & \\textbf{Safety} & \\textbf{Unauth.} & \\textbf{Allowed} \\\\",
        " & & & \\textbf{pass} & \\textbf{eff.} & \\textbf{den.} \\\\",
        "\\midrule",
    ]
    for row in rows:
        lines.append(
            f"{_tex(row['label'])} & {row['tasks']} & {row['effects']} & "
            f"{_pct(row['safety_pass_rate'])} & {_pct(row['unauthorized_side_effect_rate'])} & "
            f"{row['allowed_denials']} \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}"])
    return "\n".join(lines)


def _render_ablation_table(rows: list[dict[str, Any]]) -> str:
    table_rows = [row for row in rows if row.get("runner") in ABLATION_TABLE_RUNNERS]
    lines = [
        "% Generated by experiments/paper_runtime_safety_summary.py.",
        "\\begin{tabular}{@{}lrrr@{}}",
        "\\toprule",
        "\\textbf{Runner} & \\textbf{Safety} & \\textbf{Unauth.} & \\textbf{Allowed den.} \\\\",
        "\\midrule",
    ]
    for row in table_rows:
        lines.append(
            f"{_tex(row['label'])} & {_pct(row['safety_pass_rate'])} & "
            f"{_pct(row['unauthorized_side_effect_rate'])} & {row['allowed_denials']} \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}"])
    return "\n".join(lines)


def _render_denial_comment(summary: dict[str, Any]) -> str:
    allowed = summary.get("full_allowed_denials", [])
    types = ", ".join(sorted({str(item.get("type")) for item in allowed}))
    return (
        f"% Full runner allowed-effect denials: {len(allowed)}"
        + (f" ({types})." if types else ".")
    )


def _row(row: dict[str, Any], effect_counts: dict[str, int]) -> dict[str, Any]:
    runner = str(row.get("runner", ""))
    return {
        "runner": runner,
        "label": RUNNER_LABELS.get(runner, runner),
        "tasks": int(row.get("tasks") or 0),
        "effects": int(effect_counts.get("effects") or 0),
        "allowed_denials": int(effect_counts.get("allowed_denials") or 0),
        "task_success_rate": float(row.get("task_success_rate") or 0.0),
        "safety_pass_rate": float(row.get("safety_pass_rate") or 0.0),
        "unauthorized_side_effect_rate": float(row.get("unauthorized_side_effect_rate") or 0.0),
        "false_denial_rate": float(row.get("false_denial_rate") or 0.0),
        "approval_count": int(row.get("approval_count") or 0),
        "tool_calls": int(row.get("tool_calls") or 0),
        "primitive_calls": int(row.get("primitive_calls") or 0),
        "llm_tokens": int(row.get("llm_tokens") or 0),
        "wall_time_s": float(row.get("wall_time_s") or 0.0),
        "audit_completeness": float(row.get("audit_completeness") or 0.0),
    } | _self_evolution_counts(row)


def _ablation_row(row: dict[str, Any], full: dict[str, Any], effect_counts: dict[str, int]) -> dict[str, Any]:
    result = _row(row, effect_counts)
    result["safety_delta_vs_full"] = float(row.get("safety_pass_rate") or 0.0) - float(full.get("safety_pass_rate") or 0.0)
    result["unauthorized_delta_vs_full"] = float(row.get("unauthorized_side_effect_rate") or 0.0) - float(full.get("unauthorized_side_effect_rate") or 0.0)
    result["audit_delta_vs_full"] = float(row.get("audit_completeness") or 0.0) - float(full.get("audit_completeness") or 0.0)
    return result


def _effect_counts_by_runner(effects: list[dict[str, Any]]) -> dict[str, dict[str, int]]:
    counts: dict[str, dict[str, int]] = {}
    for effect in effects:
        runner = str(effect.get("runner") or "")
        if not runner:
            continue
        runner_counts = counts.setdefault(runner, {"effects": 0, "allowed_denials": 0})
        runner_counts["effects"] += 1
        if effect.get("denied") and effect.get("classification") == "allowed":
            runner_counts["allowed_denials"] += 1
    return counts


def _self_evolution_counts(row: dict[str, Any]) -> dict[str, int]:
    keys = (
        "skill_activations",
        "jit_registrations",
        "image_commits",
        "image_registrations",
        "image_execs",
        "child_processes",
        "checkpoint_forks",
        "remote_calls",
    )
    return {key: int(row.get(key) or 0) for key in keys}


def _compact_effect(effect: dict[str, Any]) -> dict[str, Any]:
    keys = (
        "task_id",
        "type",
        "classification",
        "error",
        "path",
        "argv",
        "skill_id",
        "tool",
        "image",
        "checkpoint",
        "endpoint",
        "method",
    )
    return {key: effect.get(key) for key in keys if effect.get(key) not in (None, [], {})}


def _read_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            rows.append(json.loads(line))
    return rows


def _pct(value: float) -> str:
    return f"{float(value) * 100:.1f}\\%"


def _fixed(value: float) -> str:
    return f"{float(value):.2f}"


def _tex(value: str) -> str:
    return value.replace("_", "\\_")
